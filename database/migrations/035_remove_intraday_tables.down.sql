-- ====================================================================
-- 35. RESTORE INTRADAY, LIVE QUOTES, NOTIFICATIONS, HOLIDAYS & DATA_PROVIDER
-- ====================================================================

-- 1. Restore data_provider column and composite index on tickers
ALTER TABLE public.tickers
ADD COLUMN IF NOT EXISTS data_provider VARCHAR(50) NOT NULL DEFAULT 'YAHOO_FINANCE';

CREATE INDEX IF NOT EXISTS idx_tickers_provider_active ON public.tickers (data_provider, is_active);

-- 2. Restore market holidays table and index
CREATE TABLE IF NOT EXISTS public.market_holidays (
    market_holiday_id INT8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country VARCHAR(10) NOT NULL,
    holiday_date DATE NOT NULL,
    name VARCHAR(255) NOT NULL,
    CONSTRAINT uk_market_holidays_country_date UNIQUE (country, holiday_date)
);

CREATE INDEX IF NOT EXISTS idx_market_holidays_lookup ON public.market_holidays (country, holiday_date);

-- 3. Restore notification logs table and index
CREATE TABLE IF NOT EXISTS public.notification_logs (
    notification_log_id INT8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message TEXT NOT NULL,
    error TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_notification_logs_created_at ON public.notification_logs (created_at DESC);

-- 4. Restore intraday prices table and index
CREATE TABLE IF NOT EXISTS public.intraday_prices (
    intraday_price_id INT8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticker_id INT8 NOT NULL,
    timeframe VARCHAR(20) NOT NULL,
    price_time TIMESTAMP WITH TIME ZONE NOT NULL,
    price_open NUMERIC(18, 4) NOT NULL,
    price_high NUMERIC(18, 4) NOT NULL,
    price_low NUMERIC(18, 4) NOT NULL,
    price_close NUMERIC(18, 4) NOT NULL,
    volume NUMERIC(18, 4) NOT NULL DEFAULT 0,
    CONSTRAINT fk_intraday_prices_ticker FOREIGN KEY (ticker_id) REFERENCES public.tickers (ticker_id) ON DELETE CASCADE,
    CONSTRAINT uk_intraday_prices UNIQUE (ticker_id, timeframe, price_time)
);

CREATE INDEX IF NOT EXISTS idx_intraday_prices_lookup ON public.intraday_prices (ticker_id, timeframe, price_time DESC);

-- 5. Restore live quotes table
CREATE TABLE IF NOT EXISTS public.live_quotes (
    live_quote_id INT8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticker_id INT8 NOT NULL,
    last_price NUMERIC(18, 4) NOT NULL,
    volume NUMERIC(18, 4) NOT NULL DEFAULT 0,
    quote_time TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_live_quotes_ticker FOREIGN KEY (ticker_id) REFERENCES public.tickers (ticker_id) ON DELETE CASCADE,
    CONSTRAINT uk_live_quotes_ticker UNIQUE (ticker_id)
);
