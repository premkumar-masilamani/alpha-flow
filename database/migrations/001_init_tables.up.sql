-- Tickers Table
CREATE TABLE public.tickers
(
    ticker_id     bigint                 NOT NULL,
    ticker_symbol varchar(255)           NOT NULL,
    ticker_name   varchar(255)           NOT NULL,
    is_active     boolean DEFAULT true   NOT NULL,

    CONSTRAINT tickers_pkey PRIMARY KEY (ticker_id),
    CONSTRAINT uk_tickers UNIQUE (ticker_symbol)
);
ALTER TABLE public.tickers
    ALTER COLUMN ticker_id ADD GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME public.tickers_ticker_id_seq);


-- Daily Prices Table
CREATE TABLE public.daily_prices
(
    daily_price_id       bigint         NOT NULL,
    price_date           date           NOT NULL,
    ticker_id            bigint         NOT NULL,
    price_open           numeric(18, 4) NOT NULL,
    price_high           numeric(18, 4) NOT NULL,
    price_low            numeric(18, 4) NOT NULL,
    price_close          numeric(18, 4) NOT NULL,
    volume               bigint         NOT NULL,

    CONSTRAINT daily_prices_pkey PRIMARY KEY (daily_price_id),
    CONSTRAINT uk_daily_prices UNIQUE (ticker_id, price_date)
);
ALTER TABLE public.daily_prices
    ALTER COLUMN daily_price_id ADD GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME public.daily_prices_id_seq);


-- Weekly Prices Table
CREATE TABLE public.weekly_prices
(
    weekly_price_id      bigint         NOT NULL,
    price_date           date           NOT NULL,
    ticker_id            bigint         NOT NULL,
    price_open           numeric(18, 4) NOT NULL,
    price_high           numeric(18, 4) NOT NULL,
    price_low            numeric(18, 4) NOT NULL,
    price_close          numeric(18, 4) NOT NULL,
    volume               bigint         NOT NULL,

    CONSTRAINT weekly_prices_pkey PRIMARY KEY (weekly_price_id),
    CONSTRAINT uk_weekly_prices UNIQUE (ticker_id, price_date)
);
ALTER TABLE public.weekly_prices
    ALTER COLUMN weekly_price_id ADD GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME public.weekly_prices_id_seq);
