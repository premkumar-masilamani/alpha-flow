CREATE TABLE backtest_results
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date          DATE           NOT NULL,
    ticker_id     INT            NOT NULL,
    strategy_name VARCHAR(100)   NOT NULL,
    equity        NUMERIC(28, 8) NOT NULL,
    position      VARCHAR(20)    NOT NULL,
    price         NUMERIC(28, 8) NOT NULL,
    signal        VARCHAR(20)    NOT NULL
);

ALTER TABLE backtest_results
    ADD CONSTRAINT fk_backtest_results_tickers
        FOREIGN KEY (ticker_id)
            REFERENCES tickers (ticker_id)
            ON DELETE CASCADE;

-- We don't add a unique constraint here because the user wants to "keep them all for references",
-- which might imply multiple runs.
