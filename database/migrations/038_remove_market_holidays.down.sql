-- 38. RESTORE MARKET HOLIDAYS TABLE
-- ==========================================

CREATE TABLE IF NOT EXISTS public.market_holidays (
    market_holiday_id INT8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country VARCHAR(10) NOT NULL,
    holiday_date DATE NOT NULL,
    name VARCHAR(255) NOT NULL,
    CONSTRAINT uk_market_holidays_country_date UNIQUE (country, holiday_date)
);

CREATE INDEX IF NOT EXISTS idx_market_holidays_lookup ON public.market_holidays (country, holiday_date);
